// Exports ABIs and deployment manifests into @namma-seva/chain (plan §8.3 step 7), replacing
// DecentraliTrack's copied src/abis/*.json and its findArtifactsBase() path lookup.
//   packages/chain/src/abis/<name>.ts   `export const projectRegistryAbi = [...] as const`
//   packages/chain/src/deployments.ts   manifests present in packages/chain/deployments/
//   pnpm --filter @namma-seva/contracts export-abis        (after `hardhat build` / deploy)
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { CHAIN_PACKAGE, CONTRACTS_ROOT } from "./lib/deployments.js";

const EXPORTED = {
  NammaSevaAccess: "contracts/NammaSevaAccess.sol/NammaSevaAccess.json",
  ProjectRegistry: "contracts/ProjectRegistry.sol/ProjectRegistry.json",
  MilestoneEscrow: "contracts/MilestoneEscrow.sol/MilestoneEscrow.json",
  GrievanceRegistry: "contracts/GrievanceRegistry.sol/GrievanceRegistry.json",
  TenderRegistry: "contracts/TenderRegistry.sol/TenderRegistry.json",
  TrustedForwarder: "contracts/governance/Imports.sol/TrustedForwarder.json",
  NammaSevaMultisig: "contracts/governance/NammaSevaMultisig.sol/NammaSevaMultisig.json",
  NammaSevaTimelock: "contracts/governance/Imports.sol/NammaSevaTimelock.json",
} as const;

const HEADER = "// Generated by packages/contracts/scripts/exportAbis.ts — do not edit.\n";
const camel = (name: string) => name[0].toLowerCase() + name.slice(1);

const abisDir = path.join(CHAIN_PACKAGE, "src", "abis");
rmSync(abisDir, { recursive: true, force: true });
mkdirSync(abisDir, { recursive: true });

const index: string[] = [HEADER];
for (const [name, rel] of Object.entries(EXPORTED)) {
  const file = path.join(CONTRACTS_ROOT, "artifacts", rel);
  if (!existsSync(file)) throw new Error(`Missing artifact ${rel} — run \`hardhat build\` first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8")) as { abi: unknown[] };
  const constName = `${camel(name)}Abi`;
  writeFileSync(
    path.join(abisDir, `${name}.ts`),
    `${HEADER}export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${constName} } from "./${name}";`);
}
writeFileSync(path.join(abisDir, "index.ts"), index.join("\n") + "\n");

// Deployments: embed public-network manifests mirrored into packages/chain/deployments.
// Local manifests (localhost) change on every `hardhat node` restart, so they stay git-ignored
// files that the API reads at runtime instead of being baked into this module.
const LOCAL_NETWORKS = new Set(["localhost", "hardhat"]);
const deploymentsDir = path.join(CHAIN_PACKAGE, "deployments");
const manifests = existsSync(deploymentsDir)
  ? readdirSync(deploymentsDir)
      .filter((f) => f.endsWith(".json") && !LOCAL_NETWORKS.has(path.basename(f, ".json")))
      .map((f) => JSON.parse(readFileSync(path.join(deploymentsDir, f), "utf8")))
  : [];

const deploymentsTs = `${HEADER}
export type ContractName = ${Object.keys(EXPORTED)
  .map((n) => `"${n}"`)
  .join(" | ")};

export type Deployment = {
  network: string;
  chainId: number;
  /** First block to index (block before the first deploy tx). */
  blockNumber: number;
  commit: string;
  deployedAt: string;
  deployer: string;
  mode: "LEDGER" | "ESCROW";
  contracts: Partial<Record<ContractName, { address: \`0x\${string}\`; implementation?: \`0x\${string}\` }>>;
};

export const DEPLOYMENTS: Record<string, Deployment> = ${JSON.stringify(
  Object.fromEntries(
    manifests.map((m) => [
      m.network,
      {
        ...m,
        contracts: Object.fromEntries(
          Object.entries(m.contracts as Record<string, { address: string; implementation?: string }>).map(([k, v]) => [
            k,
            v.implementation ? { address: v.address, implementation: v.implementation } : { address: v.address },
          ]),
        ),
      },
    ]),
  ),
  null,
  2,
)};

/** Deployment manifest for a network name, or undefined if not deployed there. */
export function getDeployment(network: string): Deployment | undefined {
  return DEPLOYMENTS[network];
}

/** Address of \`name\` on \`network\`; throws if missing so misconfiguration fails loudly at boot. */
export function contractAddress(network: string, name: ContractName): \`0x\${string}\` {
  const address = DEPLOYMENTS[network]?.contracts[name]?.address;
  if (!address) throw new Error(\`\${name} is not deployed on "\${network}"\`);
  return address;
}
`;
writeFileSync(path.join(CHAIN_PACKAGE, "src", "deployments.ts"), deploymentsTs);

console.log(
  `✓ Exported ${Object.keys(EXPORTED).length} ABIs and ${manifests.length} deployment(s) ` +
    `(${manifests.map((m) => m.network).join(", ") || "none yet"}) to @namma-seva/chain`,
);
